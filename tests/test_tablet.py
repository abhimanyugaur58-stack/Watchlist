import sys
from playwright.sync_api import sync_playwright
from common import APP_URL as URL, OUT, load_fixture, Checker, FakeTVmaze
S = str(OUT) + "/"
check = Checker()
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={"width": 800, "height": 1280}, device_scale_factor=1.5, is_mobile=True, has_touch=True)
    FakeTVmaze().attach(ctx)
    pg = ctx.new_page()
    errors = []
    pg.on("pageerror", lambda e: errors.append(str(e)))
    pg.on("console", lambda m: m.type == "error" and errors.append(m.text))
    load_fixture(pg)
    st = lambda: pg.evaluate("JSON.parse(localStorage.getItem('abhimanyu-watchlist-v2'))")
    vis = lambda sel: pg.is_visible(sel)
    box = lambda sel: pg.locator(sel).bounding_box()

    # ---------- Tablet portrait (800 wide): rail + single pane ----------
    nb = box("#tabs")
    check(nb["x"] == 0 and nb["width"] < 100 and nb["height"] > 1000, "portrait: rail on the left " + str(nb))
    check(vis("#tabs .tab.settings") and not vis("#scr-now [aria-label^='सेटिंग और बैकअप']"), "portrait: settings in rail, header gear hidden")
    cb = box("#scr-now .card[aria-label='अभी देख रहे हैं']")
    check(cb["width"] <= 690, "portrait: content kept readable width " + str(cb["width"]))
    check(pg.locator("#scr-now .upnext").count() == 3, "portrait: 3 up-next rows")
    pg.screenshot(path=S + "t01-portrait-now.png")
    pg.click("#tabs .tab >> text=सूची")
    pg.click("#scr-queue .qrow >> text=The Crown")
    check(vis("#detail-pane") and not vis("#scr-queue") and vis("#tabs"), "portrait: detail single pane, rail stays")
    pg.screenshot(path=S + "t02-portrait-detail.png")
    pg.go_back(); pg.wait_for_timeout(100)
    check(vis("#scr-queue"), "portrait: back -> queue")
    pg.click("#tabs .tab.settings")
    check(vis("#scr-settings") and vis("#tabs"), "portrait: settings with rail")
    pg.screenshot(path=S + "t03-portrait-settings.png", full_page=True)
    pg.click("#tabs .tab >> text=अभी")
    pg.wait_for_timeout(100)
    check(vis("#scr-now") and pg.evaluate("history.state.d") == 0, "portrait: rail अभी -> depth 0")

    # ---------- Tablet landscape (1280 wide): two panes ----------
    pg.set_viewport_size({"width": 1280, "height": 800})
    pg.wait_for_timeout(150)
    g = pg.evaluate("getComputedStyle(document.querySelector('#scr-now .body')).display")
    check(g == "grid", "landscape: now screen is two columns")
    check(pg.locator("#scr-now .upnext").count() == 4, "landscape: 4 up-next rows")
    pg.screenshot(path=S + "t04-landscape-now.png")
    pg.click("#scr-now .upnext >> text=House of Cards")
    pg.wait_for_timeout(100)
    check(vis("#scr-queue") and vis("#detail-pane"), "landscape: up-next opens list + detail side by side")
    check("House of Cards" in pg.inner_text("#scr-detail") and pg.evaluate("history.state.d") == 1, "landscape: HoC in right pane, depth 1")
    qb = box("#scr-queue"); db = box("#detail-pane")
    check(qb["x"] < db["x"] and 330 <= qb["width"] <= 450, "landscape: list left, detail right " + str((qb, db)))
    check(pg.locator("#scr-queue .qrow.sel").count() == 1 and "House of Cards" in pg.inner_text("#scr-queue .qrow.sel"), "landscape: selected row highlighted")
    check(not vis("#scr-detail [aria-label='वापस']"), "landscape: no back arrow in pane")
    pg.click("#scr-queue .qrow >> text=Narcos")
    check("Narcos" in pg.inner_text("#scr-detail h1") and pg.evaluate("history.state.d") == 1, "landscape: picking a row swaps the pane, no new history")
    pg.click("#scr-detail [aria-label='एक एपिसोड और देखा']")
    check(st()["progress"]["narcos"] == {"s": 1, "e": 1}, "landscape: tracker works in pane")
    pg.screenshot(path=S + "t05-landscape-queue.png")
    pg.click("#detail-actions >> text=हटाएँ")
    pg.click("#scr-detail >> text=हाँ, हटाएँ")
    pg.wait_for_timeout(150)
    check(vis("#scr-queue") and vis("#detail-pane") and "narcos" in st()["removed"], "landscape: delete keeps the list, pane moves on")
    pg.click("#snack-undo")
    check("narcos" in st()["layout"]["main"], "landscape: undo delete")
    # finished side by side
    pg.click("#tabs .tab >> text=देख लीं")
    check(vis("#scr-finished") and vis("#detail-pane") and "Peaky Blinders" in pg.inner_text("#scr-detail"), "landscape: finished list + Peaky detail")
    pg.click("#scr-finished .diary-name >> text=Game of Thrones")
    check("Game of Thrones" in pg.inner_text("#scr-detail h1"), "landscape: diary pick swaps pane")
    pg.screenshot(path=S + "t06-landscape-finished.png")
    pg.click("#tabs .tab.settings")
    g = pg.evaluate("getComputedStyle(document.querySelector('#scr-settings .body')).display")
    check(g == "grid", "landscape: settings in two columns")
    pg.screenshot(path=S + "t07-landscape-settings.png")
    pg.click("#tabs .fab")
    check(vis("#scr-add") and box("#scr-add form")["width"] <= 690, "landscape: add form readable width")
    pg.screenshot(path=S + "t08-landscape-add.png")
    pg.go_back(); pg.wait_for_timeout(100); pg.go_back(); pg.wait_for_timeout(100)

    # ---------- Turning: phone detail -> landscape ----------
    pg.set_viewport_size({"width": 390, "height": 844}); pg.wait_for_timeout(150)
    pg.click("#tabs .tab >> text=अभी"); pg.wait_for_timeout(100)
    check(not vis("#tabs .tab.settings") and box("#tabs")["y"] > 700, "phone again: bottom bar")
    pg.click("#tabs .tab >> text=सूची")
    pg.click("#scr-queue .qrow >> text=The Crown")
    check(vis("#detail-pane") and not vis("#tabs"), "phone: detail full screen")
    pg.set_viewport_size({"width": 1280, "height": 800}); pg.wait_for_timeout(150)
    check(vis("#scr-queue") and "The Crown" in pg.inner_text("#scr-detail h1"), "turned: list + Crown side by side")
    pg.click("#scr-queue .qrow >> text=Vikings"); pg.wait_for_timeout(150)
    check("Vikings" in pg.inner_text("#scr-detail h1") and pg.evaluate("history.state.d") == 1, "turned: pick another row folds history back")
    pg.set_viewport_size({"width": 390, "height": 844}); pg.wait_for_timeout(150)
    check(vis("#scr-queue") and not vis("#detail-pane"), "turned back: phone list only")

    # ---------- Phone sideways (small height) ----------
    pg.set_viewport_size({"width": 800, "height": 360}); pg.wait_for_timeout(150)
    sh = pg.evaluate("document.getElementById('tabs').scrollHeight <= document.getElementById('tabs').clientHeight + 1")
    check(sh, "phone sideways: rail fits the height")
    pg.screenshot(path=S + "t09-phone-sideways.png")
    check(not errors, "no JS errors: " + "; ".join(errors))
    b.close()
sys.exit(check.done())
